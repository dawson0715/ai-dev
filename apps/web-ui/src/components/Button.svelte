<script>
    let {
        variant = 'primary',
        size = 'md',
        type = 'button',
        disabled = false,
        loading = false,
        onclick,
        href,
        class: extraClass = '',
        children,
        ...rest
    } = $props()

    const variants = {
        primary: 'bg-brand-600 hover:bg-brand-500 text-white shadow-sm shadow-brand-900/40',
        secondary: 'bg-slate-800 hover:bg-slate-700 text-slate-100 ring-1 ring-slate-700',
        ghost: 'bg-transparent hover:bg-slate-800 text-slate-200',
        danger: 'bg-rose-600 hover:bg-rose-500 text-white'
    }
    const sizes = {
        sm: 'px-3 py-1.5 text-sm rounded-md',
        md: 'px-4 py-2 text-sm rounded-lg',
        lg: 'px-5 py-2.5 text-base rounded-lg'
    }
    const base = 'inline-flex items-center justify-center gap-2 font-medium transition-colors disabled:opacity-50 disabled:cursor-not-allowed focus:outline-none focus-visible:ring-2 focus-visible:ring-brand-500 focus-visible:ring-offset-2 focus-visible:ring-offset-slate-950'
</script>

{#if href}
    <a {href} class="{base} {variants[variant]} {sizes[size]} {extraClass}" {...rest}>
        {@render children?.()}
    </a>
{:else}
    <button {type} {disabled} {onclick} class="{base} {variants[variant]} {sizes[size]} {extraClass}" {...rest}>
        {#if loading}
            <svg class="animate-spin h-4 w-4" viewBox="0 0 24 24" fill="none">
                <circle cx="12" cy="12" r="10" stroke="currentColor" stroke-width="3" opacity="0.25"/>
                <path d="M4 12a8 8 0 018-8" stroke="currentColor" stroke-width="3" stroke-linecap="round"/>
            </svg>
        {/if}
        {@render children?.()}
    </button>
{/if}
